def create_dataset(output_path):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    rows = []
    for text in FAKE_SAMPLES:
        rows.append({'text': text.strip(), 'label': 'Fake'})
    for text in REAL_SAMPLES:
        rows.append({'text': text.strip(), 'label': 'Real'})

    with open(output_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['text', 'label'])
        writer.writeheader()
        writer.writerows(rows)

    print(f"Dataset created: {output_path}")
    print(f"Total samples: {len(rows)} ({len(FAKE_SAMPLES)} Fake, {len(REAL_SAMPLES)} Real)")
    return output_path

